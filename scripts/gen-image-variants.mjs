/**
 * Generate the smaller siblings of the static artwork, and the manifest that
 * says which files have one.
 *
 * Both sets are sized for a 3x screen at the largest place they are rendered,
 * which is correct for the top-end phone and wasteful for everything else: a
 * 2x screen — most phones, every retina laptop — downloads a file with 2.25x
 * the pixels it can show. The marquee is worse still, because the file behind
 * a card is its service's `cover`, which the homepage hero deck and the
 * service page hero also read and render four times larger.
 *
 * So each file gets one smaller copy, cut to exactly 2x its largest rendering,
 * and the components offer both through a srcset. A 3x screen still picks the
 * original; everything else stops paying for pixels it cannot draw.
 *
 * Idempotent. Run after adding or replacing artwork:
 *   node scripts/gen-image-variants.mjs
 */
import sharp from "sharp";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SUFFIX = "-sm.webp";

const SETS = [
  // Marquee tiles: 102px on a phone, 139px on a desktop. 420 covers even 3x.
  { dir: "public/services", route: "/services", width: 420, constant: "MARQUEE_SMALL_VARIANTS" },
  // Arc cards: a fixed 268px, 290px from sm up. 600 is exactly 2x.
  { dir: "public/service-cards", route: "/service-cards", width: 600, constant: "ARC_SMALL_VARIANTS" },
];

const blocks = [];
let grandBefore = 0;
let grandAfter = 0;

for (const set of SETS) {
  const sources = readdirSync(set.dir)
    .filter((f) => f.endsWith(".webp") && !f.endsWith(SUFFIX))
    .sort();

  let before = 0;
  let after = 0;

  for (const f of sources) {
    const src = join(set.dir, f);
    const out = join(set.dir, f.replace(/\.webp$/, SUFFIX));
    await sharp(src).resize({ width: set.width, withoutEnlargement: true }).webp({ quality: 78, effort: 6 }).toFile(out);
    before += statSync(src).size;
    after += statSync(out).size;
  }

  grandBefore += before;
  grandAfter += after;

  const list = sources.map((f) => `  "${set.route}/${f}",`).join("\n");
  blocks.push(
    `/** ${sources.length} files, each with a ${set.width}px "${SUFFIX}" sibling. */\n` +
      `export const ${set.constant}: ReadonlySet<string> = new Set([\n${list}\n]);`,
  );

  console.log(
    `${set.dir}: ${sources.length} at ${set.width}px — ` +
      `${(before / 1048576).toFixed(2)} MB -> ${(after / 1048576).toFixed(2)} MB ` +
      `(${(100 * (1 - after / before)).toFixed(0)}% smaller)`,
  );
}

writeFileSync(
  "lib/marquee-variants.ts",
  `// Generated by scripts/gen-image-variants.mjs — do not edit by hand.\n` +
    `//\n` +
    `// A component checks membership here before offering a srcset, because a\n` +
    `// derived filename that does not exist is a 404 inside a srcset and\n` +
    `// browsers do not fall back from those.\n\n` +
    blocks.join("\n\n") +
    `\n\n/** The smaller sibling of a path known to be in one of the sets above. */\n` +
    `export function smallVariant(path: string): string {\n` +
    `  return path.slice(0, -".webp".length) + "${SUFFIX}";
` +
    `}\n`,
  "utf8",
);

console.log(
  `TOTAL ${(grandBefore / 1048576).toFixed(2)} MB -> ${(grandAfter / 1048576).toFixed(2)} MB ` +
    `(${((grandBefore - grandAfter) / 1048576).toFixed(2)} MB saved)`,
);
